window.onload = function () {
  // Get the element
  var box = document.getElementById("main");
  var box2 = document.getElementById("name");
  var box3 = document.getElementById("first");
  var box4 = document.getElementById("second");

  // Add the class to trigger the animation
  box.classList.add("animate-loaded");
  box2.classList.add("animate-loaded-name");
  box3.classList.add("first-technology-name-animation");
  box4.classList.add("second-technology-name-animation");
};
